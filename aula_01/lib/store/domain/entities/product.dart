class Product {
  final int id;
  final String nome;
  final String categoria;
  final double preco;
  final double avaliacao;
  final String imagemUrl;

  Product({
    required this.id,
    required this.nome,
    required this.categoria,
    required this.preco,
    required this.avaliacao,
    required this.imagemUrl,
  });
}